"""Build identical ``build_packs/{triposr,tripo,hi3d,rodin}/`` trees."""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image

from composite3dgen.composites.select import AngleSelection, MissingFrontError
from composite3dgen.manifest import SubjectManifest
from composite3dgen.manifest.loader import CARDINAL_ANGLES

BUILD_PACK_PROVIDERS = ("triposr", "tripo", "hi3d", "rodin")


class MissingFrontPackError(ValueError):
    """Raised when pack generation is rejected for a missing front JPEG."""


@dataclass
class PackBuildResult:
    """Paths written under ``job_dir/build_packs``."""

    packs_root: Path
    providers: list[str] = field(default_factory=list)
    pack_dirs: dict[str, Path] = field(default_factory=dict)
    angles_written: dict[str, str] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)


def _jpeg_name(angle: str) -> str:
    return f"{angle}.jpg"


def _write_jpeg(src: Path, dest: Path, *, quality: int = 92) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(src) as img:
        rgb = img.convert("RGB")
        rgb.save(dest, format="JPEG", quality=quality, optimize=True)


def _pack_readme(
    *,
    provider: str,
    subject_id: str,
    domain: str,
    angles: dict[str, Path],
    executor_name: str,
) -> str:
    angle_lines = "\n".join(
        f"- `{_jpeg_name(angle)}` ← `{path.name}`" for angle, path in sorted(angles.items())
    )
    return f"""# Build pack — {provider}

Subject: `{subject_id}` (domain: `{domain}`)

Identical cardinal composites for provider intake. Generated by Composite3DGen U2
pack builder. Prefer running ingest / quality / packs on **MWT1**; this pack was
produced via executor `{executor_name}` (controller local is degraded fallback).

## Cardinals

{angle_lines}

## Notes

- Packs **must** include `front.jpg` (rejected otherwise).
- `triposr` is local single-image draft reconstruct — not Tripo cloud multiview.
- Paid providers (`tripo`, `hi3d`, `rodin`) stay behind `--spend` (U3+).
"""


def build_provider_packs(
    job_dir: Path,
    selection: AngleSelection,
    manifest: SubjectManifest,
    *,
    executor_name: str = "local",
    providers: tuple[str, ...] = BUILD_PACK_PROVIDERS,
) -> PackBuildResult:
    """Write identical provider packs under ``job_dir/build_packs``.

    Rejects the entire build if ``front`` is missing from ``selection``.
    """
    job_dir = Path(job_dir)
    try:
        selection.require_front()
    except MissingFrontError as exc:
        raise MissingFrontPackError(str(exc)) from exc

    if "front" not in selection.angles:
        raise MissingFrontPackError(
            "Canonical front view is missing; packs are rejected without front."
        )

    # Ensure required cardinals when declared; front already enforced.
    missing_required = [
        angle
        for angle in manifest.angles_required
        if angle not in selection.angles
    ]
    # Soft-warn non-front required; hard-fail only on front (per U2 contract).
    notes: list[str] = []
    if missing_required:
        notes.append(
            "Missing non-front required angles (pack still written with front): "
            + ", ".join(missing_required)
        )

    packs_root = job_dir / "build_packs"
    packs_root.mkdir(parents=True, exist_ok=True)

    # Materialize JPEGs once into a staging area, then copy identically.
    staging = job_dir / "manifests" / "_pack_staging"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True, exist_ok=True)

    angles_written: dict[str, str] = {}
    for angle, src in selection.angles.items():
        dest = staging / _jpeg_name(angle)
        _write_jpeg(src, dest)
        angles_written[angle] = dest.name

    # Always confirm front.jpg exists in staging.
    front_jpeg = staging / "front.jpg"
    if not front_jpeg.is_file():
        raise MissingFrontPackError("front.jpg was not written; rejecting packs")

    result = PackBuildResult(
        packs_root=packs_root,
        angles_written=angles_written,
        notes=notes,
    )

    meta = {
        "subject_id": manifest.subject_id,
        "domain": manifest.domain,
        "angles": angles_written,
        "executor": executor_name,
        "providers": list(providers),
        "cardinals": [a for a in CARDINAL_ANGLES if a in angles_written],
    }
    (job_dir / "manifests").mkdir(parents=True, exist_ok=True)
    meta_path = job_dir / "manifests" / "pack_angles.json"
    meta_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")

    for provider in providers:
        pack_dir = packs_root / provider
        if pack_dir.exists():
            shutil.rmtree(pack_dir)
        pack_dir.mkdir(parents=True, exist_ok=True)
        for jpeg in staging.glob("*.jpg"):
            shutil.copy2(jpeg, pack_dir / jpeg.name)
        readme = _pack_readme(
            provider=provider,
            subject_id=manifest.subject_id,
            domain=manifest.domain,
            angles=selection.angles,
            executor_name=executor_name,
        )
        (pack_dir / "README.md").write_text(readme, encoding="utf-8")
        if not (pack_dir / "front.jpg").is_file():
            raise MissingFrontPackError(
                f"Pack {provider} missing front.jpg after write; rejecting"
            )
        result.providers.append(provider)
        result.pack_dirs[provider] = pack_dir

    result.notes.append(
        f"Wrote identical packs for {', '.join(providers)} under {packs_root}"
    )
    return result
